/**
 * DDL sources (#67): an ORM's DDL read into declarations, and `yodel new`
 * building them beside src/. The claim (declarative, its orm part) proves
 * plan and apply on a server.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { checkYodelConfig } from "../src/config/load.js";
import { ddlToDeclarations } from "../src/sources/ddl.js";
import { readMigrations } from "../src/migrations/index.js";
import { json, projectFrom, repoRoot, yodel } from "./helpers/run.js";

const prisma = readFileSync(join(repoRoot, "scenarios", "fixtures", "postgres", "orm", "schema.sql"), "utf8");

describe("ddlToDeclarations", () => {
  it("reads Prisma's DDL: the schema qualifies each name, the foreign key folds into its table, the enum column is the enum", async () => {
    const d = await ddlToDeclarations("postgres", prisma, { origin: "prisma", schema: "app" });
    expect(d.objects.map((o) => `${o.type} ${o.name}`)).toEqual([
      "Postgres::Enum app.Tier",
      "Postgres::Table app.customers",
      "Postgres::Table app.invoices",
      "Postgres::Index app.customers_email_key",
    ]);
    expect(d.content).toContain('CREATE TABLE app."customers"');
    expect(d.content).toContain('"tier" ${tier} NOT NULL');
    expect(d.content).toMatch(/CONSTRAINT "invoices_customer_id_fkey" FOREIGN KEY \("customer_id"\) REFERENCES \$\{customers\}\("id"\)/);
    expect(d.content).toContain('CREATE UNIQUE INDEX "customers_email_key" ON ${customers}("email")');
    expect(d.content).not.toContain("ALTER TABLE");
  });

  it("refuses a statement it cannot declare, naming it", async () => {
    await expect(ddlToDeclarations("postgres", `${prisma}\nINSERT INTO "customers" ("email") VALUES ('a');\nALTER TABLE "customers" DROP COLUMN "tier";`, { origin: "prisma" })).rejects.toThrow(
      /prisma: 2 statements chant cannot read[\s\S]*not a statement that declares an object: INSERT INTO[\s\S]*an ALTER TABLE other than ADD of a table constraint[^\n]*: ALTER TABLE "customers" DROP[\s\S]*A DDL source holds/,
    );
  });

  it("reads ClickHouse DDL, qualified with the database", async () => {
    const ddl = readFileSync(join(repoRoot, "scenarios", "fixtures", "clickhouse", "orm", "schema.sql"), "utf8");
    const d = await ddlToDeclarations("clickhouse", ddl, { origin: "orm", schema: "shop" });
    expect(d.objects.map((o) => o.name)).toEqual(["shop.customers", "shop.invoices"]);
  });
});

describe("sources in yodel.config.ts", () => {
  it("takes one of command and file", () => {
    expect(() => checkYodelConfig({ sources: { orm: { command: "x", file: "y" } } }, "yodel.config.ts")).toThrow(/give one of command and file/);
    expect(() => checkYodelConfig({ sources: { Orm: { file: "y" } } }, "yodel.config.ts")).toThrow(/lowercase/);
    expect(() => checkYodelConfig({ sources: { orm: { file: "y", schemas: "app" } } }, "yodel.config.ts")).toThrow(/unknown setting/);
    expect(checkYodelConfig({ sources: { orm: { command: "cat db.sql", schema: "app" } } }, "yodel.config.ts")).toBeTruthy();
  });
});

describe("yodel new with a DDL source", () => {
  const EMULATOR_ENV = ["YODEL_E2E_CLICKHOUSE_URL", "YODEL_E2E_POSTGRES_URL"];
  const saved = Object.fromEntries(EMULATOR_ENV.map((k) => [k, process.env[k]]));
  beforeAll(() => {
    process.env.YODEL_E2E_CLICKHOUSE_URL = "http://127.0.0.1:9";
    process.env.YODEL_E2E_POSTGRES_URL = "postgres://127.0.0.1:9/postgres";
  });
  afterAll(() => {
    for (const k of EMULATOR_ENV) {
      const v = saved[k];
      if (v === undefined) Reflect.deleteProperty(process.env, k);
      else process.env[k] = v;
    }
  });
  const config = (source: string) => `export default { sources: { prisma: ${source} } };\n`;

  it("writes the ORM's tables into the migration, and refuses an object src/ also declares", async () => {
    const { dir, dispose } = projectFrom("postgres");
    try {
      writeFileSync(join(dir, "prisma.sql"), prisma);
      writeFileSync(join(dir, "yodel.config.ts"), config(`{ command: "cat prisma.sql", schema: "yodel_e2e_fixture" }`));
      const made = await yodel(["new", "orm", "--json", "--dir", dir]);
      expect(made.code, made.err).toBe(0);
      expect(json(made)).toMatchObject({ written: true });
      expect(readFileSync(join(dir, "src", "prisma.generated.ts"), "utf8")).toMatch(/^\/\/ Generated by yodel from the DDL source "prisma"/);
      const [migration] = readMigrations(join(dir, "migrations"));
      expect(migration?.files.sql).toMatch(/CREATE TABLE yodel_e2e_fixture\."?invoices"?/);

      writeFileSync(join(dir, "prisma.sql"), `${prisma}\nCREATE TABLE "orders" ("id" bigint);\n`);
      const twice = await yodel(["new", "again", "--dir", dir]);
      expect(twice.code).toBe(1);
      expect(twice.err).toMatch(/yodel_e2e_fixture\.orders is declared twice: by src\/ \(export orders\) and by the source "prisma"/);
    } finally {
      dispose();
    }
  }, 120_000);

  it("needs no source for a plain .sql file in src/: chant's build reads it", async () => {
    const { dir, dispose } = projectFrom("postgres");
    try {
      writeFileSync(join(dir, "src", "extra.sql"), "CREATE TABLE yodel_e2e_fixture.extra (\n  id bigint PRIMARY KEY,\n  note text\n);\n");
      const made = await yodel(["new", "extra", "--json", "--dir", dir]);
      expect(made.code, made.err).toBe(0);
      const [migration] = readMigrations(join(dir, "migrations"));
      expect(migration?.files.sql).toMatch(/CREATE TABLE yodel_e2e_fixture\.extra/);
    } finally {
      dispose();
    }
  }, 120_000);
});
