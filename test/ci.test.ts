/**
 * `yodel ci` (#65): the pipelines rendered by the package, the forges
 * yodel.config.ts `ci.forges` picks, and the project's own jobs (`ci.jobs`)
 * merged after yodel's and kept on every render.
 */

import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { parseYAMLDocument } from "@intentius/chant/yaml";
import { checkYodelConfig } from "../src/config/load.js";
import { repoRoot, yodel } from "./helpers/run.js";

const temps: string[] = [];
afterAll(() => {
  for (const t of temps) rmSync(t, { recursive: true, force: true });
});

/** A copy of the ClickHouse template, resolving chant and the lexicons from this checkout. */
function project(ci: string, jobs?: string): string {
  const dir = mkdtempSync(join(tmpdir(), "yodel-ci-"));
  temps.push(dir);
  cpSync(join(repoRoot, "templates", "clickhouse"), dir, { recursive: true });
  symlinkSync(join(repoRoot, "node_modules"), join(dir, "node_modules"));
  const config = join(dir, "yodel.config.ts");
  const text = readFileSync(config, "utf8").replace(/^ {2}ci: .*$/m, `  ci: ${ci},`);
  writeFileSync(config, text);
  if (jobs !== undefined) writeFileSync(join(dir, "jobs.ts"), jobs);
  // chant finds the Ops from the git root.
  execFileSync("git", ["init", "-q"], { cwd: dir });
  return dir;
}

const JOBS = `import { Job, Step } from "@intentius/chant-lexicon-github";
import { Image, Job as GitLabJob } from "@intentius/chant-lexicon-gitlab";

export const actions = {
  unit: new Job({ "runs-on": "ubuntu-latest", steps: [new Step({ run: "echo the project's own job" })] }),
};
export const gitlab = {
  unit: new GitLabJob({ stage: "test", image: new Image({ name: "node:22" }), script: ["echo the project's own job"] }),
};
`;

describe("yodel ci", () => {
  it("renders the forges ci.forges names, with the project's own jobs after yodel's, and keeps them on every render", async () => {
    const dir = project('{ forges: ["github", "gitlab"], jobs: "jobs.ts" }', JOBS);
    const wrote = await yodel(["ci", "--dir", dir]);
    expect(wrote.code, wrote.err).toBe(0);
    expect(existsSync(join(dir, ".github/workflows/yodel-pr.yml"))).toBe(true);
    expect(wrote.out).not.toContain(".forgejo/");

    const pr = parseYAMLDocument(readFileSync(join(dir, ".github/workflows/yodel-pr.yml"), "utf8")) as { jobs: Record<string, { steps: Array<{ run?: string }> }> };
    expect(Object.keys(pr.jobs)).toEqual(["lint", "plan-dev", "plan-prod", "unit"]);
    expect(pr.jobs.unit?.steps[0]?.run).toBe("echo the project's own job");
    const gitlab = parseYAMLDocument(readFileSync(join(dir, ".gitlab-ci.yml"), "utf8")) as Record<string, unknown> & { stages: string[] };
    expect(gitlab.stages).toEqual(["review", "test", "wave-1-dev", "wave-2-prod", "ops"]);
    expect(gitlab.unit).toMatchObject({ stage: "test", script: ["echo the project's own job"] });

    expect((await yodel(["ci", "--check", "--dir", dir])).code).toBe(0);
    // A pipeline edited by hand, or rendered by an older yodel: --check names it, and yodel ci renders it again, the project's job kept.
    const file = join(dir, ".github/workflows/yodel-pr.yml");
    writeFileSync(file, readFileSync(file, "utf8").replace(/\n {2}unit:\n[\s\S]*$/, "\n"));
    const stale = await yodel(["ci", "--check", "--dir", dir]);
    expect(stale.code).toBe(1);
    expect(stale.err).toContain("stale, run yodel ci: .github/workflows/yodel-pr.yml");
    expect((await yodel(["ci", "--dir", dir])).out).toBe("wrote .github/workflows/yodel-pr.yml\n");
    expect(readFileSync(file, "utf8")).toContain("echo the project's own job");
  });

  it("checks sql-types.d.ts in the lint job when the project commits one (#228), and not otherwise", async () => {
    const lintRuns = (dir: string): Array<string | undefined> => {
      const pr = parseYAMLDocument(readFileSync(join(dir, ".github/workflows/yodel-pr.yml"), "utf8")) as { jobs: Record<string, { steps: Array<{ run?: string }> }> };
      return (pr.jobs.lint?.steps ?? []).map((s) => s.run);
    };
    const plain = project('{ forges: ["github", "gitlab"] }');
    expect((await yodel(["ci", "--dir", plain])).code).toBe(0);
    expect(lintRuns(plain)).not.toContain("chant sql types --check");

    const typed = project('{ forges: ["github", "gitlab"] }');
    writeFileSync(join(typed, "src", "sql-types.d.ts"), "// Generated by chant\nexport {};\n");
    const wrote = await yodel(["ci", "--dir", typed]);
    expect(wrote.code, wrote.err).toBe(0);
    const runs = lintRuns(typed);
    // After the pipelines' own check, before yodel lint.
    expect(runs.indexOf("chant sql types --check")).toBe(runs.indexOf("yodel ci --check") + 1);
    const gitlab = parseYAMLDocument(readFileSync(join(typed, ".gitlab-ci.yml"), "utf8")) as { lint: { script: string[] } };
    expect(gitlab.lint.script.slice(0, 2)).toEqual(["yodel ci --check", "chant sql types --check"]);
  });

  it("refuses a project job named as one of yodel's, and a jobs module that is not there", async () => {
    const clash = project('{ forges: ["github"], jobs: "jobs.ts" }', JOBS.replace("unit: new Job", "lint: new Job"));
    const ran = await yodel(["ci", "--dir", clash]);
    expect(ran.code).toBe(1);
    expect(ran.err).toContain("actions job lint has the name of one of yodel's jobs");
    const missing = project('{ jobs: "nowhere.ts" }');
    expect((await yodel(["ci", "--dir", missing])).err).toContain("ci.jobs names nowhere.ts, which is not there");
  });

  it("checks yodel.config.ts ci", () => {
    expect(() => checkYodelConfig({ ci: { forges: ["github", "bitbucket"] } }, "yodel.config.ts")).toThrow(/ci\.forges: a list of github, gitlab, forgejo/);
    expect(() => checkYodelConfig({ ci: { forges: [] } }, "yodel.config.ts")).toThrow(/ci\.forges/);
    expect(() => checkYodelConfig({ ci: { jobs: 3 } }, "yodel.config.ts")).toThrow(/ci\.jobs/);
    expect(() => checkYodelConfig({ ci: { image: "ghcr.io/intentius/sql-yodeler:0.3.0" } }, "yodel.config.ts")).toThrow(/ci\.image: the CI image pinned by its digest/);
    expect(() => checkYodelConfig({ ci: { color: "x" } }, "yodel.config.ts")).toThrow(/ci\.color: unknown setting/);
    expect(checkYodelConfig({ ci: { forges: ["gitlab"], jobs: "ci/jobs.ts" } }, "yodel.config.ts").ci).toEqual({ forges: ["gitlab"], jobs: "ci/jobs.ts" });
  });

  it("with ci.image, runs every job in the yodel image by its digest, and installs nothing (#66)", async () => {
    const image = `ghcr.io/intentius/sql-yodeler:0.3.0@sha256:${"a".repeat(64)}`;
    const dir = project(`{ image: "${image}" }`);
    const wrote = await yodel(["ci", "--dir", dir]);
    expect(wrote.code, wrote.err).toBe(0);
    const rendered = wrote.out.trim().split("\n").map((l) => l.replace(/^wrote /, ""));
    expect(rendered).toHaveLength(11);
    for (const f of rendered) {
      const text = readFileSync(join(dir, f), "utf8");
      expect(text, f).not.toContain("npm ci");
      expect(text, f).not.toContain("node_modules/.bin");
      expect(text, f).not.toContain("setup-node");
      expect(text, f).not.toContain("node:22-bookworm");
      expect(text, f).toContain(image);
    }
    // Every Actions job in the container, the plan jobs on GitHub's VM too, and the report from the image's yodel.
    for (const f of [".github/workflows/yodel-pr.yml", ".github/workflows/yodel-apply.yml", ".github/workflows/watch-dev.yml"]) {
      const doc = parseYAMLDocument(readFileSync(join(dir, f), "utf8")) as { jobs: Record<string, { container?: unknown; steps: Array<{ run?: string }> }> };
      for (const [name, job] of Object.entries(doc.jobs)) expect(job.container, `${f} ${name}`).toBe(image);
    }
    expect(readFileSync(join(dir, ".gitlab-ci.yml"), "utf8")).toContain("; yodel report dev --json");
  });

  it("with ci.resume, renders the scheduled resume job on each forge, with that forge's least token (#47)", async () => {
    const dir = project('{ resume: { schedule: "*/10 * * * *" } }');
    const wrote = await yodel(["ci", "--dir", dir]);
    expect(wrote.code, wrote.err).toBe(0);
    type ResumeDoc = { on: { schedule: Array<{ cron: string }> }; permissions?: Record<string, string>; jobs: { resume: { steps: Array<{ run?: string; env?: Record<string, string> }> } } };
    const read = (f: string) => parseYAMLDocument(readFileSync(join(dir, f), "utf8")) as ResumeDoc;
    const step = (doc: ResumeDoc) => doc.jobs.resume.steps.find((s) => s.run === "chant run resume --op yodel-apply");

    // GitHub: the job's own token, allowed to re-run a run and nothing more.
    const github = read(".github/workflows/yodel-apply-resume.yml");
    expect(github.on.schedule).toEqual([{ cron: "*/10 * * * *" }]);
    expect(github.permissions).toEqual({ contents: "read", actions: "write" });
    expect(step(github)?.env).toEqual({ GITHUB_TOKEN: "${{ github.token }}" });
    // Forgejo: no re-run API, and the job's token cannot dispatch; a write:repository token in CHANT_FORGE_TOKEN.
    const forgejo = read(".forgejo/workflows/yodel-apply-resume.yml");
    expect(forgejo.on.schedule).toEqual([{ cron: "*/10 * * * *" }]);
    expect(step(forgejo)?.env).toEqual({ CHANT_FORGE_TOKEN: "${{ secrets.CHANT_FORGE_TOKEN }}" });
    expect(readFileSync(join(dir, ".forgejo/workflows/yodel-apply-resume.yml"), "utf8")).toContain("write:repository");
    // The fetch of chant/lifecycle before it, where the approvals are.
    for (const doc of [github, forgejo]) expect(doc.jobs.resume.steps.some((s) => s.run?.includes("refs/heads/chant/lifecycle"))).toBe(true);

    // GitLab: a schedule-only job in the apply file, its stage in the main file, and a Developer token named.
    const apply = parseYAMLDocument(readFileSync(join(dir, ".gitlab/yodel-apply.gitlab-ci.yml"), "utf8")) as Record<string, { stage?: string; rules?: unknown; script?: string[] }>;
    expect(apply["yodel-apply-resume"]).toMatchObject({ stage: "resume", rules: [{ if: '$CI_PIPELINE_SOURCE == "schedule"' }] });
    expect(apply["yodel-apply-resume"]?.script?.at(-1)).toBe("chant run resume --op yodel-apply");
    const main = readFileSync(join(dir, ".gitlab-ci.yml"), "utf8");
    expect((parseYAMLDocument(main) as { stages: string[] }).stages).toEqual(["review", "wave-1-dev", "wave-2-prod", "resume", "ops"]);
    expect(main).toContain("GITLAB_TOKEN: a project access token with the api scope (Developer)");

    // The spec the wave jobs read is the same with or without it.
    expect(JSON.parse(readFileSync(join(dir, "yodel-waves.json"), "utf8"))).not.toHaveProperty("resume");
    expect((await yodel(["ci", "--check", "--dir", dir])).code).toBe(0);
  });

  it("renders no resume job without ci.resume", async () => {
    const dir = project('{ forges: ["github", "gitlab", "forgejo"] }');
    expect((await yodel(["ci", "--dir", dir])).code).toBe(0);
    expect(existsSync(join(dir, ".github/workflows/yodel-apply-resume.yml"))).toBe(false);
    expect(existsSync(join(dir, ".forgejo/workflows/yodel-apply-resume.yml"))).toBe(false);
    expect(readFileSync(join(dir, ".gitlab/yodel-apply.gitlab-ci.yml"), "utf8")).not.toContain("resume");
  });

  it("runs yodel test after the replay check, on its server, when the project has tests/*.test.ts (#54)", async () => {
    const dir = project('{ forges: ["github", "gitlab", "forgejo"] }');
    expect((await yodel(["ci", "--dir", dir])).code).toBe(0);
    expect(readFileSync(join(dir, ".github/workflows/yodel-pr.yml"), "utf8")).not.toContain("yodel test");
    mkdirSync(join(dir, "tests"));
    writeFileSync(join(dir, "tests", "events.test.ts"), "export default [];\n");
    expect((await yodel(["ci", "--dir", dir])).code).toBe(0);
    for (const file of [".github/workflows/yodel-pr.yml", ".forgejo/workflows/yodel-pr.yml", ".gitlab-ci.yml"]) {
      const text = readFileSync(join(dir, file), "utf8");
      const replay = text.indexOf("yodel lint --replay replay --reset");
      const test = text.indexOf("yodel test --env replay --reset --junit yodel-test.xml");
      expect(replay, file).toBeGreaterThan(0);
      expect(test, file).toBeGreaterThan(replay);
    }
  });

  it("with ci.apply: false, renders the pull request checks and the watches on each forge, and no apply pipeline (#175)", async () => {
    const dir = project('{ forges: ["github", "gitlab", "forgejo"], apply: false }');
    // The template's rendered pipelines out of the way, so the render shows every file it writes.
    for (const f of [".github", ".forgejo", ".gitlab", ".gitlab-ci.yml", "yodel-waves.json"]) rmSync(join(dir, f), { recursive: true, force: true });
    const wrote = await yodel(["ci", "--dir", dir]);
    expect(wrote.code, wrote.err).toBe(0);
    const rendered = wrote.out.trim().split("\n").map((l) => l.replace(/^wrote /, "")).sort();
    expect(rendered).toEqual([
      ".forgejo/workflows/watch-dev.yml",
      ".forgejo/workflows/watch-prod.yml",
      ".forgejo/workflows/yodel-pr.yml",
      ".github/workflows/watch-dev.yml",
      ".github/workflows/watch-prod.yml",
      ".github/workflows/yodel-pr.yml",
      ".gitlab-ci.yml",
      ".gitlab/yodel-watch.gitlab-ci.yml",
    ]);
    // No file in the project names a writer.
    for (const f of rendered) expect(readFileSync(join(dir, f), "utf8"), f).not.toMatch(/WRITER|writer:/);
    const gitlab = parseYAMLDocument(readFileSync(join(dir, ".gitlab-ci.yml"), "utf8")) as { stages: string[]; include: Array<{ local: string }> };
    expect(gitlab.stages).toEqual(["review", "ops"]);
    expect(gitlab.include).toEqual([{ local: ".gitlab/yodel-watch.gitlab-ci.yml" }]);
    const pr = parseYAMLDocument(readFileSync(join(dir, ".github/workflows/yodel-pr.yml"), "utf8")) as { jobs: Record<string, { steps: Array<{ run?: string }> }> };
    expect(Object.keys(pr.jobs)).toEqual(["lint", "plan-dev", "plan-prod"]);
    expect(pr.jobs["plan-prod"]?.steps.some((st) => st.run === "yodel config check prod dev --write-probe")).toBe(true);
    const check = await yodel(["ci", "--check", "--dir", dir]);
    expect(check.code, check.err).toBe(0);
    expect(check.out).toBe("8 CI files are up to date\n");
  });

  it("refuses ci.apply: false with a pr-review wave or with ci.resume, naming the setting (#175)", () => {
    expect(() => checkYodelConfig({ ci: { apply: false }, waves: [{ env: "dev", gate: "always" }, { env: "prod", gate: "always", approval: "pr-review" }] }, "yodel.config.ts")).toThrow(
      /waves\[1\]\.approval: pr-review .* remove waves\[1\]\.approval, or ci\.apply/,
    );
    expect(() => checkYodelConfig({ ci: { apply: false, resume: { schedule: "*/10 * * * *" } } }, "yodel.config.ts")).toThrow(/remove ci\.resume, or ci\.apply/);
    expect(() => checkYodelConfig({ ci: { apply: "no" } }, "yodel.config.ts")).toThrow(/ci\.apply: true \(the default\) or false/);
    expect(checkYodelConfig({ ci: { apply: false }, waves: [{ env: "dev", gate: "always", approval: "sealed" }] }, "yodel.config.ts").ci).toEqual({ apply: false });
    expect(checkYodelConfig({ ci: { apply: true, resume: { schedule: "*/10 * * * *" } } }, "yodel.config.ts").ci).toMatchObject({ apply: true });
  });

  it("checks ci.resume's schedule", () => {
    expect(() => checkYodelConfig({ ci: { resume: { schedule: "every ten minutes" } } }, "yodel.config.ts")).toThrow(/ci\.resume: \{ schedule \} with a five-field cron/);
    expect(() => checkYodelConfig({ ci: { resume: { schedule: "*/10 * * * *", by: "me" } } }, "yodel.config.ts")).toThrow(/ci\.resume/);
    expect(checkYodelConfig({ ci: { resume: { schedule: "*/10 * * * *" } } }, "yodel.config.ts").ci).toEqual({ resume: { schedule: "*/10 * * * *" } });
  });

  it("takes --check or --replay, not both, and options after -- only with --replay", async () => {
    expect((await yodel(["ci", "--check", "--replay"])).err).toContain("--check and --replay are two things");
    expect((await yodel(["ci", "--", "--json"])).err).toContain("options after -- are for --replay");
  });
});
